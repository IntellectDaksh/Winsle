/**
 * Converts a hex color string (#RRGGBB) to a normalized [0..1] RGB tuple.
 */
export function hexToRGB(hex: string): RGB {
  const h = hex.replace("#", "").trim();
  const v = parseInt(h, 16);
  if (Number.isNaN(v)) return [0, 0, 0];
  return [((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255];
}

/**
 * Formats a normalized RGB tuple into a standard CSS rgba string.
 */
export function rgba(c: RGB, a = 1): string {
  const r = Math.round(c[0] * 255);
  const g = Math.round(c[1] * 255);
  const b = Math.round(c[2] * 255);
  const alpha = Math.max(0, Math.min(1, a));
  return `rgba(${r},${g},${b},${alpha})`;
}

/**
 * Linearly interpolates two RGB colors.
 */
export function mix3(a: RGB, b: RGB, t: number): RGB {
  const clampedT = Math.max(0, Math.min(1, t));
  return [
    lerp(a[0], b[0], clampedT),
    lerp(a[1], b[1], clampedT),
    lerp(a[2], b[2], clampedT),
  ];
}

/**
 * Returns eye shape for an emote or state.
 */
export function getEmoteEye(emote: BotEmoteName): EyeShape {
  return EMOTE_EYE[emote] ?? "pill";
}
